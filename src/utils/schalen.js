// Haal bedrag op voor een specifiek label (bijv. "01.05") en CAO versie
export function getBedragForLabel(schaal, trede, caoVersie) {
  const label = `${schaal}.${trede.padStart(2, '0')}`
  const schalenArray = caoMappingHelper[caoVersie] || schalenArray2026_1
  const item = schalenArray.find((item) => item.label.trim() === label.trim())
  return item ? item.value : null
}

// Vind de eerstvolgende hogere schaal en trede op basis van een bedrag
export function findNextHigherSchaalTrede(currentBedrag, startSchaal, caoVersie) {
  const schalenArray = caoMappingHelper[caoVersie] || schalenArray2026_1
  const startIndex = schaalOrder.indexOf(startSchaal)

  if (startIndex === -1) return null

  // Zoek alleen in hogere schalen
  for (let i = startIndex + 1; i < schaalOrder.length; i++) {
    const schaal = schaalOrder[i]
    const prefix = schaal + '.'

    // Vind alle items in deze schaal
    const itemsInSchaal = schalenArray
      .filter((item) => item.label.trim().startsWith(prefix))
      .sort((a, b) => a.value - b.value)

    // Vind eerste item met waarde gelijk of hoger dan currentBedrag
    const nextItem = itemsInSchaal.find((item) => item.value >= currentBedrag)

    if (nextItem) {
      const label = nextItem.label.trim()
      const parts = label.split('.')
      return {
        schaal: parts[0],
        trede: parts[1],
        bedrag: nextItem.value,
      }
    }
  }

  return null // Geen hogere schaal/trede gevonden
}

// Verhoog de trede met een bepaald aantal stappen
export function getTredeNStepsHigher(schaal, trede, steps, caoVersie) {
  const schalenArray = caoMappingHelper[caoVersie] || schalenArray2026_1
  const currentLabel = `${schaal}.${trede.padStart(2, '0')}`

  // Vind het huidige item
  const currentItem = schalenArray.find((item) => item.label.trim() === currentLabel.trim())
  if (!currentItem) return null

  // Vind alle items in dezelfde schaal
  const prefix = schaal + '.'
  const itemsInSchaal = schalenArray
    .filter((item) => item.label.trim().startsWith(prefix))
    .sort((a, b) => a.value - b.value)

  // Vind de index van het huidige item
  const currentIndex = itemsInSchaal.findIndex((item) => item.label.trim() === currentLabel.trim())
  if (currentIndex === -1) return null

  // Bereken de nieuwe index
  const newIndex = currentIndex + steps
  if (newIndex < 0 || newIndex >= itemsInSchaal.length) return null

  const newItem = itemsInSchaal[newIndex]
  const label = newItem.label.trim()
  const parts = label.split('.')

  return {
    schaal: parts[0],
    trede: parts[1],
    bedrag: newItem.value,
  }
}
